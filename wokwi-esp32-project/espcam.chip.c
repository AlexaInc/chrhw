// ============================================================================
//  ESP32-CAM (serial protocol) chip for Wokwi  -  single file, drop-in
// ----------------------------------------------------------------------------
//  This chip replaces the whole ESP32-CAM board of your robot. Wire it to the
//  main board's UART0 (TX0 / RX0) exactly like the real camera:
//
//        main board TX0 ──────► chip RX
//        main board RX0 ◄────── chip TX
//
//  It speaks the same protocol as your camera firmware, at 921600 baud:
//
//        main board :  'C'
//        chip       :  "<IMG:2945>" followed by 2945 raw JPEG bytes
//
//  So Serial.find("<IMG:"), Serial.parseInt(), Serial.read()=='>' and
//  Serial.readBytes(imgBuffer, imgSize) in captureAndUploadImage() all work
//  with the main-board code COMPLETELY UNCHANGED. No shim header, no
//  #ifdef, nothing added to the sketch.
//
//  Pins
//      GND  VCC   power (cosmetic)
//      RX         <- main board TX0 (GPIO1)
//      TX         -> main board RX0 (GPIO3)
//      TRIG       rising edge = take a photo (push button, optional)
//      BUSY       HIGH while the image is being sent (LED, optional)
//
//  Controls
//      scene            0 colour bars · 1 leaf · 2 no answer (timeout test)
//                       3 truncated image (tests the "Partial image" branch)
//      captureLatencyMs delay between 'C' and the "<IMG:" header
//      triggerMode      0 smart (default) · 1 any 'C' byte · 2 TRIG pin only
//      idleGapMs        smart mode: silence required before a bare 'C'
//
//  Why "smart" trigger mode is the default: your main board shares UART0
//  between the Serial Monitor and the camera, so every [DEBUG] line is also
//  sent to this chip. Letters 'C' inside words like "[CAM]" or "CONNECTED"
//  must NOT fire the shutter. In smart mode a 'C' only counts when it is the
//  first byte of a line (right after \n or \r) or arrives after a quiet gap -
//  which is exactly how Serial.print('C') appears on the wire.
// ============================================================================

